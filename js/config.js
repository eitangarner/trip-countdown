/**
 * Generates a flag emoji from a 2-letter ISO 3166-1 alpha-2 code using Unicode Regional Indicators.
 * @param {string} countryCode
 * @returns {string}
 */
export function getCountryFlag(countryCode) {
  return String.fromCodePoint(
    ...[...countryCode.toUpperCase()].map((char) => 0x1f1e6 + char.charCodeAt(0) - 65)
  );
}

/**
 * Resolves CountryInfo dynamically using native Intl APIs (Intl.DisplayNames + Intl.Locale timeZones).
 * @param {string} countryCode
 * @returns {CountryInfo}
 */
export function getCountryInfo(countryCode) {
  const code = countryCode.toUpperCase();
  const locale = new Intl.Locale(`und-${code}`);
  const zones = locale.getTimeZones?.() ?? locale.timeZones ?? ['UTC'];
  const timeZone = MULTI_ZONE_PRIMARY[code] ?? zones[0] ?? 'UTC';
  return {
    code,
    name: REGION_NAMES.of(code) || code,
    flag: getCountryFlag(code),
    timeZone,
    region: timeZone.split('/')[0]
  };
}

