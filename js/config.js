/**
 * Lazily-populated catalog of all 249 ISO 3166-1 countries.
 * Avoids running 249 Intl.Locale instantiations synchronously before the lock screen renders.
 * @type {Record<string, CountryInfo>}
 */
export const COUNTRY_CATALOG = new Proxy(/** @type {Record<string, CountryInfo>} */ ({}), {
  get(target, prop) {
    if (typeof prop === 'string' && /^[A-Z]{2}$/i.test(prop)) {
      const upper = prop.toUpperCase();
      if (!target[upper] && ALL_ISO_3166_CODES.includes(upper)) {
        target[upper] = getCountryInfo(upper);
      }
      return target[upper];
    }
    return Reflect.get(target, prop);
  },
  ownKeys(target) {
    if (Object.keys(target).length < ALL_ISO_3166_CODES.length) {
      for (const code of ALL_ISO_3166_CODES) {
        if (!target[code]) {
          target[code] = getCountryInfo(code);
        }
      }
    }
    return Reflect.ownKeys(target);
  },
  getOwnPropertyDescriptor(target, prop) {
    if (typeof prop === 'string' && ALL_ISO_3166_CODES.includes(prop.toUpperCase())) {
      const upper = prop.toUpperCase();
      if (!target[upper]) {
        target[upper] = getCountryInfo(upper);
      }
      return {
        enumerable: true,
        configurable: true,
        value: target[upper]
      };
    }
    return Reflect.getOwnPropertyDescriptor(target, prop);
  }
});
